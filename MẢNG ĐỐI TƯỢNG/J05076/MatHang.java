package J05076;

public class MatHang {
    private String id, name, rank;
    public MatHang(String id, String name, String rank) {
        this.id = id;
        this.name = name;
        this.rank = rank;
    }
    public String getId() {
        return id;
    }
    public String getName() {
        return name;
    }
    public String getRank() {
        return rank;
    }
}
